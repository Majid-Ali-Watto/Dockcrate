import { generate } from '../src/generate.js';
import { SAMPLE_DIR, landingBySlug } from '../lib/landing.js';
import { requireAllowedHost } from '../lib/site.js';
import SiteFooter from './SiteFooter.jsx';
import SiteHeader from './SiteHeader.jsx';

/** Server-rendered guide page: plain HTML a crawler reads without running the generator UI. */
export default async function Landing({ slug }) {
  await requireAllowedHost();
  const page = landingBySlug(slug);
  const sample = generate(SAMPLE_DIR, page.sample.opts).files.find((f) => f.path === page.sample.file);
  return (
    <div className="site">
      <SiteHeader />
      <main className="wrap wrap-narrow doc">
        <nav className="crumbs" aria-label="Breadcrumb">
          <a href="/">Home</a>
          <span aria-hidden="true">/</span>
          <span aria-current="page">{page.nav}</span>
        </nav>
        <h1>{page.h1}</h1>
        <p className="section-lead">{page.lead}</p>
        <p>
          <a className="btn btn-primary btn-lg" href="/generator">
            Generate your files
          </a>
        </p>

        <h2>What you get</h2>
        <ul className="ticks">
          {page.points.map((text) => (
            <li key={text}>{text}</li>
          ))}
        </ul>

        <h2>Sample output</h2>
        <figure className="window">
          <div className="window-bar">
            <span className="dots" aria-hidden="true">
              <i />
              <i />
              <i />
            </span>
            <span className="window-name">{sample.path}</span>
          </div>
          <pre tabIndex={0} aria-label={`${sample.path} sample`}>
            <code>{sample.content}</code>
          </pre>
          <figcaption className="muted">{page.sample.caption}. Generated by Dockcrate.</figcaption>
        </figure>

        <h2>How it works</h2>
        <ol className="doc-steps">
          <li>Pick a stack and the options you need.</li>
          <li>Preview every file, and edit or switch off any block.</li>
          <li>Copy the files or download them as a zip.</li>
        </ol>

        <h2>Questions</h2>
        {page.faq.map(([question, answer]) => (
          <details key={question} className="faq">
            <summary>{question}</summary>
            <p>{answer}</p>
          </details>
        ))}
      </main>
      <SiteFooter />
    </div>
  );
}
