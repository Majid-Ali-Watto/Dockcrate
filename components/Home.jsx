import { generate } from '../src/generate.js';
import { isHosted } from '../src/api.js';
import { requireAllowedHost } from '../lib/site.js';
import { FEATURES, HOME_FAQ, PROVIDERS, STACKS, STEPS, TARGETS } from '../lib/home.js';
import { LANDING, SAMPLE_DIR } from '../lib/landing.js';
import SiteFooter from './SiteFooter.jsx';
import SiteHeader from './SiteHeader.jsx';

const SAMPLE_OPTS = { stack: 'node', tool: 'npm', name: 'web' };

function Chips({ title, items }) {
  return (
    <div className="chips-group">
      <h3>{title}</h3>
      <ul className="chips">
        {items.map((item) => (
          <li key={item}>{item}</li>
        ))}
      </ul>
    </div>
  );
}

/** The landing page: server-rendered text a crawler reads without running the generator. */
export default async function Home() {
  await requireAllowedHost();
  const dockerfile = generate(SAMPLE_DIR, SAMPLE_OPTS).files.find((f) => f.path === 'Dockerfile');
  const privacy = isHosted() ? 'Free. No sign-up. Nothing you enter is stored.' : 'Free. Runs locally: nothing leaves your machine.';
  return (
    <div className="site">
      <SiteHeader />
      <main>
        <section className="hero">
          <div className="wrap hero-grid">
            <div>
              <p className="eyebrow">{privacy}</p>
              <h1>Docker &amp; CI/CD file generator</h1>
              <p className="hero-lead">
                Pick a stack and get a Dockerfile, docker-compose, CI/CD pipeline and deployment config for your new project, ready to copy or download.
              </p>
              <p className="hero-actions">
                <a className="btn btn-primary btn-lg" href="/generator">
                  Open the generator
                </a>
                <a className="btn btn-ghost btn-lg" href="#sample">
                  See sample output
                </a>
              </p>
              <p className="muted hero-note">
                {STACKS.length} stacks · {PROVIDERS.length} CI providers · {TARGETS.length} deploy options
              </p>
            </div>
            <figure className="window" id="sample">
              <div className="window-bar">
                <span className="dots" aria-hidden="true">
                  <i />
                  <i />
                  <i />
                </span>
                <span className="window-name">Dockerfile</span>
              </div>
              <pre tabIndex={0} aria-label="Dockerfile sample">
                <code>{dockerfile.content}</code>
              </pre>
              <figcaption className="muted">Generated by Dockcrate for a Node.js project with npm.</figcaption>
            </figure>
          </div>
        </section>

        <section className="band">
          <div className="wrap">
            <h2>Everything a new project needs</h2>
            <p className="section-lead">One set of choices, every file consistent with the others.</p>
            <ul className="cards">
              {FEATURES.map((f) => (
                <li key={f.title} className="card">
                  <h3>{f.title}</h3>
                  <p>{f.text}</p>
                  {f.slug && (
                    <a className="card-link" href={`/${f.slug}`}>
                      {LANDING.find((page) => page.slug === f.slug).nav} guide
                    </a>
                  )}
                </li>
              ))}
            </ul>
          </div>
        </section>

        <section className="band band-alt">
          <div className="wrap">
            <h2>How it works</h2>
            <ol className="steps">
              {STEPS.map(([title, text], i) => (
                <li key={title} className="step">
                  <span className="step-n" aria-hidden="true">
                    {i + 1}
                  </span>
                  <h3>{title}</h3>
                  <p>{text}</p>
                </li>
              ))}
            </ol>
          </div>
        </section>

        <section className="band">
          <div className="wrap">
            <h2>Stacks, providers and targets</h2>
            <Chips title="Stacks" items={STACKS} />
            <Chips title="CI providers" items={PROVIDERS} />
            <Chips title="Deploy to" items={TARGETS} />
          </div>
        </section>

        <section className="band band-alt">
          <div className="wrap">
            <h2>Guides</h2>
            <ul className="cards cards-quad">
              {LANDING.map((page) => (
                <li key={page.slug} className="card">
                  <h3>
                    <a href={`/${page.slug}`}>{page.nav}</a>
                  </h3>
                  <p>{page.lead}</p>
                </li>
              ))}
            </ul>
          </div>
        </section>

        <section className="band">
          <div className="wrap wrap-narrow">
            <h2>Questions</h2>
            {HOME_FAQ.map(([question, answer]) => (
              <details key={question} className="faq">
                <summary>{question}</summary>
                <p>{answer}</p>
              </details>
            ))}
            <p className="cta-end">
              <a className="btn btn-primary btn-lg" href="/generator">
                Open the generator
              </a>
            </p>
          </div>
        </section>
      </main>
      <SiteFooter />
    </div>
  );
}
