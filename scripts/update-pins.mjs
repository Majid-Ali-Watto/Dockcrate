#!/usr/bin/env node
// Resolves every `uses: owner/repo@ref` the generator can emit to a full commit SHA and writes src/providers/pins.js.
// Needs git and network access; run it after adding or bumping an action:  npm run pins
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));

const used = new Set();
for (const file of walk(join(ROOT, 'src')).filter((f) => f.endsWith('.js') && !f.endsWith('pins.js'))) {
  for (const m of readFileSync(file, 'utf8').matchAll(/uses:\s*'([^']+@[^']+)'/g)) used.add(m[1]);
}

function resolve(uses) {
  const [name, ref] = uses.split('@');
  const repo = name.split('/').slice(0, 2).join('/');
  const run = spawnSync('git', ['ls-remote', `https://github.com/${repo}`, `refs/tags/${ref}`, `refs/tags/${ref}^{}`, `refs/heads/${ref}`], { encoding: 'utf8' });
  const rows = run.stdout.trim().split('\n').filter(Boolean).map((l) => l.split(/\s+/));
  // An annotated tag lists the tag object first and the commit it points to as `^{}`.
  const row = rows.find((r) => r[1].endsWith('^{}')) ?? rows[0];
  if (run.status !== 0 || !row) throw new Error(`cannot resolve ${uses} in ${repo}`);
  return row[0];
}

const pins = Object.fromEntries([...used].sort().map((u) => [u, resolve(u)]));
const body = Object.entries(pins).map(([u, sha]) => `  '${u}': '${sha}',`).join('\n');
writeFileSync(
  join(ROOT, 'src/providers/pins.js'),
  `// Generated by scripts/update-pins.mjs (npm run pins): do not edit by hand.
// Full commit SHAs for the actions the generator emits, so workflows reference immutable code instead of a movable tag.
export const PINS = {
${body}
};

/** \`owner/repo@v4\` -> \`owner/repo@<sha> # v4\`; an action without a pin is returned unchanged. */
export function pinAction(uses) {
  const sha = PINS[uses];
  if (!sha) return uses;
  const at = uses.lastIndexOf('@');
  return \`\${uses.slice(0, at)}@\${sha} # \${uses.slice(at + 1)}\`;
}
`,
);
console.log(`pinned ${used.size} actions`);
